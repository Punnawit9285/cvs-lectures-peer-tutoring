/* node tools/join.js: assemble the per-section parts (parts/<S>.<layer>.js) into the files the pages load.
   data/lite.js, src/thai-data.js, src/thai-explain.js, src/tutor-notes.js, src/tutor-script.js,
   src/flows-anatomy.js and src/flows-charts.js are generated: edit the parts, then run this. */
const fs = require('fs'), path = require('path');
process.chdir(path.join(__dirname, '..'));
const secs = JSON.parse(fs.readFileSync('data/sections.json', 'utf8')).filter(s => !['lib', 'figs', 'lite'].includes(s));
const rd = f => fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/\s+$/, '') + '\n' : '';
const gen = '/* GENERATED by tools/join.js from parts/ — do not edit here. */\n';
const cat = (layer) => secs.map(s => rd('parts/' + s + '.' + layer + '.js')).filter(Boolean).join('\n');
const out = {
  'data/lite.js': rd('parts/_lite-head.js') + '\n' + cat('lite'),
  'src/thai-data.js': gen + 'window.THAI_Q = window.THAI_Q || {};\nwindow.THAI_CONCEPT = window.THAI_CONCEPT || {};\nwindow.THAI_SEC = window.THAI_SEC || {};\n\n' + cat('thai'),
  'src/thai-explain.js': gen + 'window.THAI_EXPLAIN = window.THAI_EXPLAIN || {};\n\n' + cat('explain'),
  'src/tutor-notes.js': gen + 'window.TUTOR_NOTES = window.TUTOR_NOTES || {};\n\n' + cat('notes'),
  'src/tutor-script.js': gen + rd('parts/_plan.js') + '\n' + cat('script'),
  'src/flows-anatomy.js': rd('parts/_maps-head.js') + '\n' + cat('map') + '})();\n',
  'src/flows-charts.js': gen + '(function () {\n  var F = window.FLOWS;\n  if (!F || !F.add) return;\n  function ul(a) { return \'<ul>\' + a.map(function (x) { return \'<li>\' + x + \'</li>\'; }).join(\'\') + \'</ul>\'; }\n' + cat('chart') + '})();\n'
};
for (const [f, t] of Object.entries(out)) fs.writeFileSync(f, t);
console.log('joined', secs.length, 'sections:', Object.keys(out).map(f => f + ' ' + out[f].length).join(', '));
