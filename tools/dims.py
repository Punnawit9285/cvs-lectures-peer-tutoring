#!/usr/bin/env python3
"""Write data/figs.js: pixel size of every figure in img/*.jpg (read by CVS.fig for width/height attributes)."""
import os, glob
from PIL import Image
os.chdir(os.path.join(os.path.dirname(__file__), '..'))
fs = sorted(glob.glob('img/*.jpg'))
with open('data/figs.js', 'w') as o:
    o.write('/* Generated by tools/dims.py from img/*.jpg. */\nCVS.dims = {\n')
    o.write(',\n'.join('  "%s": [%d, %d]' % ((os.path.basename(f)[:-4],) + Image.open(f).size) for f in fs))
    o.write('\n};\n')
print(len(fs), 'figures in data/figs.js')
